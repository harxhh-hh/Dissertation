"""Structured logging for every LLM interaction in the experiment.

The dissertation's central claim is a comparison between agent collaboration
architectures. That claim is only auditable if every model call is recorded in
full, so this module writes two artefacts per run:

``llm_interactions.jsonl``
    One JSON object per line, one line per LLM call (successful or failed).
    This is the primary evidence base: it records the architecture, agent,
    model, exact prompt, exact response, token counts, latency and timestamp,
    which is enough to reconstruct cost, latency and behaviour post hoc.

``run.log``
    A human-readable narrative of the run, for debugging and for including as
    an appendix.

Design decisions worth noting for the reader:

* **Nothing is swallowed.** Failed calls are written to the JSONL file with
  an ``error`` object and re-raised by the caller. A run that degrades must
  do so visibly.
* **Append-only, flushed per record.** If a run crashes half-way, everything
  up to the crash is already on disk.
* **Thread-safe.** Writes are guarded by a lock so that architectures which
  later run agents concurrently do not interleave partial lines.

Note on the module name: this file is ``utils/logging.py`` but, because Python
3 uses absolute imports, ``import logging`` below still resolves to the
standard library module, not to this file.

Typical use::

    with ExperimentLogger.for_run(settings) as logger:
        logger.log_interaction(
            architecture="hierarchical",
            agent="functional_requirements",
            ...
        )
"""

from __future__ import annotations

import json
import logging
import sys
import threading
import time
import uuid
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from pathlib import Path
from types import TracebackType
from typing import Any, Iterator, Mapping, Sequence

# Imported for the convenience constructor and for type hints only; this
# module does not otherwise depend on configuration.
from config.settings import Settings

#: Name of the JSON Lines file holding one record per LLM call.
INTERACTIONS_FILENAME = "llm_interactions.jsonl"

#: Name of the human-readable run log.
RUN_LOG_FILENAME = "run.log"

#: Name of the redacted configuration snapshot written at run start.
CONFIG_SNAPSHOT_FILENAME = "config.json"

_LOG_FORMAT = "%(asctime)s | %(levelname)-8s | %(name)s | %(message)s"
_LOG_DATEFMT = "%Y-%m-%dT%H:%M:%S%z"


def _utc_now_iso() -> str:
    """Return the current UTC time as an ISO-8601 string with a ``Z`` suffix."""
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace(
        "+00:00", "Z"
    )


