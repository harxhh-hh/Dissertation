class ExperimentLogger:
    """Writes the run log and the LLM interaction log for a single run.

    Use :meth:`for_run` to construct one from a :class:`~config.settings.Settings`
    object, which also creates the run directory and writes the configuration
    snapshot. The logger is a context manager and should be closed so that
    file handles are released and the end-of-run summary is written.

    Args:
        run_dir: Directory to write artefacts into. Created if absent.
        run_id: Identifier stamped onto every interaction record.
        log_level: Verbosity for the console and ``run.log`` handlers.
    """

    def __init__(self, run_dir: Path, run_id: str, log_level: str = "INFO") -> None:
        self.run_dir = run_dir
        self.run_id = run_id
        self.run_dir.mkdir(parents=True, exist_ok=True)

        self.interactions_path = self.run_dir / INTERACTIONS_FILENAME
        self.run_log_path = self.run_dir / RUN_LOG_FILENAME

        self.totals = RunTotals()

        self._lock = threading.Lock()
        self._closed = False
        # Line-buffered append: each record is on disk as soon as it is written,
        # so a crash mid-run still leaves a usable partial log.
        self._interactions_file = self.interactions_path.open(
            "a", encoding="utf-8", buffering=1
        )
        self._logger = self._build_logger(log_level)

        self._logger.info("Run %s started; artefacts in %s", run_id, self.run_dir)

    # -- construction -------------------------------------------------------

    @classmethod
    def for_run(cls, settings: Settings) -> "ExperimentLogger":
        """Create a logger for ``settings`` and snapshot the configuration.

        Creates the run directory, writes the redacted ``config.json``
        provenance record, and returns a ready-to-use logger.

        Args:
            settings: The resolved configuration for this run.

        Returns:
            An open :class:`ExperimentLogger`.
        """
        run_dir = settings.ensure_run_dir()
        logger = cls(run_dir=run_dir, run_id=settings.run_id, log_level=settings.log_level)
        snapshot_path = run_dir / CONFIG_SNAPSHOT_FILENAME
        snapshot_path.write_text(
            json.dumps(settings.to_dict(), indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        logger.info("Configuration snapshot written to %s", snapshot_path)
        return logger

    def _build_logger(self, log_level: str) -> logging.Logger:
        """Configure a private stdlib logger with file and console handlers.

        A per-run logger name keeps handlers isolated, so constructing a second
        logger (e.g. in a test) does not duplicate the first one's output.
        """
        logger = logging.getLogger(f"experiment.{self.run_id}")
        logger.setLevel(log_level)
        logger.propagate = False
        logger.handlers.clear()

        formatter = logging.Formatter(_LOG_FORMAT, datefmt=_LOG_DATEFMT)

        file_handler = logging.FileHandler(self.run_log_path, encoding="utf-8")
        file_handler.setFormatter(formatter)
        logger.addHandler(file_handler)

        console_handler = logging.StreamHandler(sys.stderr)
        console_handler.setFormatter(formatter)
        logger.addHandler(console_handler)

        return logger

    # -- external handlers ---------------------------------------------------

    def add_handler(self, handler: logging.Handler) -> None:
        """Attach an extra handler to the run's narrative logger.

        Lets a caller (e.g. the Streamlit UI) observe the same INFO/WARNING/
        ERROR narrative lines already written to ``run.log`` and the console
        — without this module knowing anything about who's listening. The
        handler receives every record from the moment it is attached, in
        the same thread that issues the LLM calls, so a handler that pushes
        into a UI placeholder sees updates as soon as each call completes.

        Args:
            handler: A configured ``logging.Handler``. Its own formatter (if
                any) is left untouched; a plain default formatter is not
                imposed so the caller controls the display format.
        """
        self._logger.addHandler(handler)

    # -- narrative logging --------------------------------------------------

    def debug(self, message: str, *args: Any) -> None:
        """Log a DEBUG-level message to the run log and console."""
        self._logger.debug(message, *args)

    def info(self, message: str, *args: Any) -> None:
        """Log an INFO-level message to the run log and console."""
        self._logger.info(message, *args)

    def warning(self, message: str, *args: Any) -> None:
        """Log a WARNING-level message to the run log and console."""
        self._logger.warning(message, *args)

    def error(self, message: str, *args: Any, exc_info: bool = False) -> None:
        """Log an ERROR-level message, optionally with a traceback."""
        self._logger.error(message, *args, exc_info=exc_info)

    # -- interaction logging ------------------------------------------------

    def log_interaction(
        self,
        *,
        architecture: str,
        agent: str,
        case_id: str,
        repetition: int,
        phase: str,
        model: str,
        system_prompt: str,
        messages: Sequence[Mapping[str, Any]],
        request_params: Mapping[str, Any],
        response_text: str,
        stop_reason: str | None,
        usage: TokenUsage,
        latency_ms: float,
        error: Mapping[str, Any] | None = None,
    ) -> LLMInteraction:
        """Record one LLM call and append it to ``llm_interactions.jsonl``.

        Args:
            architecture: Condition under test.
            agent: Agent role that issued the call.
            case_id: Test case identifier.
            repetition: Zero-based repetition index.
            phase: Stage within the architecture's protocol.
            model: Model identifier used.
            system_prompt: System prompt sent, verbatim.
            messages: ``messages`` array sent, verbatim.
            request_params: Non-prompt request parameters.
            response_text: Concatenated response text (empty on failure).
            stop_reason: Reported stop reason, if any.
            usage: Token accounting for the call.
            latency_ms: Wall-clock duration in milliseconds.
            error: Error details if the call failed, else ``None``.

        Returns:
            The :class:`LLMInteraction` that was written.

        Raises:
            RuntimeError: If the logger has already been closed.
        """
        interaction = LLMInteraction(
            interaction_id=uuid.uuid4().hex,
            run_id=self.run_id,
            timestamp=_utc_now_iso(),
            architecture=architecture,
            agent=agent,
            case_id=case_id,
            repetition=repetition,
            phase=phase,
            model=model,
            system_prompt=system_prompt,
            messages=list(messages),
            request_params=dict(request_params),
            response_text=response_text,
            stop_reason=stop_reason,
            usage=usage,
            latency_ms=round(latency_ms, 1),
            error=dict(error) if error is not None else None,
        )
        self._write_interaction(interaction)
        return interaction

    def _write_interaction(self, interaction: LLMInteraction) -> None:
        """Serialise one interaction to the JSONL file and update totals."""
        if self._closed:
            raise RuntimeError(
                "ExperimentLogger is closed; cannot record further interactions."
            )

        line = json.dumps(interaction.to_json_dict(), ensure_ascii=False)
        with self._lock:
            self._interactions_file.write(line + "\n")
            self.totals.add(interaction)

        if interaction.error is not None:
            self.error(
                "LLM call FAILED | %s/%s | case=%s rep=%d phase=%s | %s: %s",
                interaction.architecture,
                interaction.agent,
                interaction.case_id,
                interaction.repetition,
                interaction.phase,
                interaction.error.get("type", "UnknownError"),
                interaction.error.get("message", ""),
            )
            return

        if interaction.stop_reason not in (None, "end_turn"):
            # Not fatal, but it means the response may be truncated or refused;
            # surface it rather than letting it pass unnoticed into the results.
            self.warning(
                "Unexpected stop_reason=%r | %s/%s | case=%s rep=%d phase=%s",
                interaction.stop_reason,
                interaction.architecture,
                interaction.agent,
                interaction.case_id,
                interaction.repetition,
                interaction.phase,
            )

        self.info(
            "LLM call | %s/%s | case=%s rep=%d phase=%s | "
            "in=%d out=%d tokens | %.0f ms",
            interaction.architecture,
            interaction.agent,
            interaction.case_id,
            interaction.repetition,
            interaction.phase,
            interaction.usage.total_input_tokens,
            interaction.usage.output_tokens,
            interaction.latency_ms,
        )

    # -- timing helper ------------------------------------------------------

    @staticmethod
    def start_timer() -> float:
        """Return a monotonic start time for use with :meth:`elapsed_ms`."""
        return time.perf_counter()

    @staticmethod
    def elapsed_ms(started_at: float) -> float:
        """Return milliseconds elapsed since ``started_at``."""
        return (time.perf_counter() - started_at) * 1000.0

    # -- reading back -------------------------------------------------------

    def iter_interactions(self) -> Iterator[dict[str, Any]]:
        """Yield every interaction recorded so far, in write order.

        Reads the JSONL file from disk, so it also works for runs logged by a
        previous process (useful for the analysis scripts in later stages).

        Yields:
            One decoded JSON object per recorded interaction.
        """
        if not self.interactions_path.exists():
            return
        with self.interactions_path.open("r", encoding="utf-8") as handle:
            for line in handle:
                line = line.strip()
                if line:
                    yield json.loads(line)

    # -- lifecycle ----------------------------------------------------------

    def close(self) -> None:
        """Write the end-of-run summary and release file handles.

        Safe to call more than once.
        """
        if self._closed:
            return

        summary = self.totals.to_dict()
        summary_path = self.run_dir / "run_summary.json"
        summary_path.write_text(
            json.dumps({"run_id": self.run_id, **summary}, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        self.info(
            "Run %s finished | %d calls (%d failed) | %d in / %d out tokens | %.1f s",
            self.run_id,
            summary["calls"],
            summary["failed_calls"],
            summary["input_tokens"],
            summary["output_tokens"],
            summary["latency_ms"] / 1000.0,
        )

        with self._lock:
            self._interactions_file.close()
            self._closed = True

        for handler in list(self._logger.handlers):
            handler.close()
            self._logger.removeHandler(handler)

    def __enter__(self) -> "ExperimentLogger":
        """Enter the context manager, returning this logger."""
        return self

    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        traceback: TracebackType | None,
    ) -> bool:
        """Log any propagating exception, then close. Never suppresses."""
        if exc is not None:
            self.error("Run %s aborted: %s: %s", self.run_id, exc_type.__name__ if exc_type else "?", exc, exc_info=True)
        self.close()
        return False
