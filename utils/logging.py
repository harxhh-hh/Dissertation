@dataclass(frozen=True)
class TokenUsage:
    """Token accounting for a single LLM call.

    Attributes:
        input_tokens: Uncached input tokens billed at full rate.
        output_tokens: Tokens generated by the model (including any thinking
            tokens, which are billed as output).
        cache_creation_input_tokens: Input tokens written to the prompt cache.
        cache_read_input_tokens: Input tokens served from the prompt cache.
    """

    input_tokens: int = 0
    output_tokens: int = 0
    cache_creation_input_tokens: int = 0
    cache_read_input_tokens: int = 0

    @property
    def total_input_tokens(self) -> int:
        """Total input tokens processed, cached or not.

        The API reports ``input_tokens`` as the *uncached remainder* only, so
        the true prompt size is the sum of all three input fields.
        """
        return (
            self.input_tokens
            + self.cache_creation_input_tokens
            + self.cache_read_input_tokens
        )

    @property
    def total_tokens(self) -> int:
        """Total tokens processed and generated for this call."""
        return self.total_input_tokens + self.output_tokens

    @classmethod
    def from_response_usage(cls, usage: Any) -> "TokenUsage":
        """Build a :class:`TokenUsage` from an SDK response ``usage`` object.

        Args:
            usage: The ``usage`` attribute of an Anthropic ``Message``. Fields
                absent on the object default to ``0``, so this tolerates SDK
                versions that do not report cache statistics.

        Returns:
            A populated :class:`TokenUsage`.
        """
        return cls(
            input_tokens=int(getattr(usage, "input_tokens", 0) or 0),
            output_tokens=int(getattr(usage, "output_tokens", 0) or 0),
            cache_creation_input_tokens=int(
                getattr(usage, "cache_creation_input_tokens", 0) or 0
            ),
            cache_read_input_tokens=int(
                getattr(usage, "cache_read_input_tokens", 0) or 0
            ),
        )


@dataclass(frozen=True)
class LLMInteraction:
    """A complete record of one call to the language model.

    One of these is written per line to ``llm_interactions.jsonl``. The field
    set is deliberately wide: it is cheaper to record a field now than to
    re-run a paid experiment because a column was missing at analysis time.

    Attributes:
        interaction_id: Unique identifier for this call.
        run_id: Identifier of the run this call belongs to.
        timestamp: UTC ISO-8601 timestamp taken when the call was issued.
        architecture: Condition under test — one of ``hierarchical``,
            ``peer_to_peer``, ``debate``, or ``baseline_single_prompt``.
        agent: Agent role that issued the call (e.g. ``orchestrator``), or
            ``baseline`` for the single-prompt condition.
        case_id: Identifier of the test case being processed.
        repetition: Zero-based repetition index for this (architecture, case)
            pair, used to quantify run-to-run variance.
        phase: Stage within the architecture (e.g. ``initial``, ``review``,
            ``revision``, ``arbitration``), for tracing multi-round protocols.
        model: Model identifier used for this call.
        system_prompt: The system prompt sent, verbatim.
        messages: The ``messages`` array sent, verbatim.
        request_params: Non-prompt request parameters (max_tokens, effort,
            thinking mode), recorded so the exact call can be reconstructed.
        response_text: Concatenated text content of the response.
        stop_reason: Why generation stopped (``end_turn``, ``max_tokens``,
            ``refusal``, ...). Anything other than ``end_turn`` warrants
            scrutiny during analysis.
        usage: Token accounting for the call.
        latency_ms: Wall-clock duration of the call in milliseconds.
        error: Populated only when the call failed; ``None`` otherwise.
    """

    interaction_id: str
    run_id: str
    timestamp: str
    architecture: str
    agent: str
    case_id: str
    repetition: int
    phase: str
    model: str
    system_prompt: str
    messages: Sequence[Mapping[str, Any]]
    request_params: Mapping[str, Any]
    response_text: str
    stop_reason: str | None
    usage: TokenUsage
    latency_ms: float
    error: Mapping[str, Any] | None = None

    def to_json_dict(self) -> dict[str, Any]:
        """Return a JSON-serialisable dictionary for the JSONL file."""
        record = asdict(self)
        record["usage"]["total_input_tokens"] = self.usage.total_input_tokens
        record["usage"]["total_tokens"] = self.usage.total_tokens
        return record


@dataclass
class RunTotals:
    """Running aggregates over a run, used for the end-of-run summary.

    Attributes:
        calls: Number of LLM calls issued, including failed ones.
        failed_calls: Number of calls that raised.
        input_tokens: Sum of all input tokens (cached and uncached).
        output_tokens: Sum of all output tokens.
        latency_ms: Sum of per-call wall-clock latency.
    """

    calls: int = 0
    failed_calls: int = 0
    input_tokens: int = 0
    output_tokens: int = 0
    latency_ms: float = 0.0

    def add(self, interaction: LLMInteraction) -> None:
        """Accumulate one interaction into the totals."""
        self.calls += 1
        if interaction.error is not None:
            self.failed_calls += 1
        self.input_tokens += interaction.usage.total_input_tokens
        self.output_tokens += interaction.usage.output_tokens
        self.latency_ms += interaction.latency_ms

    def to_dict(self) -> dict[str, Any]:
        """Return a JSON-serialisable snapshot of the totals."""
        return {
            "calls": self.calls,
            "failed_calls": self.failed_calls,
            "input_tokens": self.input_tokens,
            "output_tokens": self.output_tokens,
            "total_tokens": self.input_tokens + self.output_tokens,
            "latency_ms": round(self.latency_ms, 1),
        }


